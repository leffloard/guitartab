// Generates src/analysis.gen.ts from schema/analysis.schema.json.
// The schema itself is exported from the Python analyzer (Pydantic models are the source of truth):
//   cd services/analyzer && uv run python -m barrefree_analyzer.export_schema
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

import { compile, type JSONSchema } from 'json-schema-to-typescript'

const schemaUrl = new URL('../schema/analysis.schema.json', import.meta.url)
const outUrl = new URL('../src/analysis.gen.ts', import.meta.url)

const schema = JSON.parse(await readFile(schemaUrl, 'utf8')) as JSONSchema
const ts = await compile(schema, 'AnalysisResult', {
  bannerComment:
    '/* This file is generated by scripts/generate.ts from schema/analysis.schema.json. Do not edit by hand. */',
  additionalProperties: false,
  unreachableDefinitions: true,
  cwd: fileURLToPath(new URL('../schema/', import.meta.url)),
})
await writeFile(outUrl, ts)
console.log(`wrote ${fileURLToPath(outUrl)}`)
