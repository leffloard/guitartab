// Generates src/analysis.gen.ts from schema/analysis.schema.json.
// The schema itself is exported from the Python analyzer (Pydantic models are the source of truth):
//   cd services/analyzer && uv run barrefree-export-schema
//
//   node scripts/generate.ts           # write the file
//   node scripts/generate.ts --check   # fail if the committed file is stale
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

import { compile, type JSONSchema } from 'json-schema-to-typescript'
import { format, resolveConfig } from 'prettier'

const schemaUrl = new URL('../schema/analysis.schema.json', import.meta.url)
const outUrl = new URL('../src/analysis.gen.ts', import.meta.url)
const outPath = fileURLToPath(outUrl)

const schema = JSON.parse(await readFile(schemaUrl, 'utf8')) as JSONSchema
const ts = await compile(schema, 'AnalysisResult', {
  bannerComment:
    '/* This file is generated by scripts/generate.ts from schema/analysis.schema.json. Do not edit by hand. */',
  additionalProperties: false,
  unreachableDefinitions: true,
  format: false,
  cwd: fileURLToPath(new URL('../schema/', import.meta.url)),
})
const formatted = await format(ts, { ...(await resolveConfig(outPath)), parser: 'typescript' })

if (process.argv.includes('--check')) {
  const current = await readFile(outUrl, 'utf8').catch(() => '')
  if (current !== formatted) {
    console.error(`${outPath} is stale: run \`pnpm gen:contracts\``)
    process.exit(1)
  }
  console.log(`${outPath} is up to date`)
} else {
  await writeFile(outUrl, formatted)
  console.log(`wrote ${outPath}`)
}
